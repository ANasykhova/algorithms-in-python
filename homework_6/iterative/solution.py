"""
№ 2. Iterative
Итеративные версии mergesort и quicksort (без рекурсии)

Решение:
Mergesort (снизу вверх)
1) считаем каждый элемент отсортированным отрезком длины size = 1
2) за один проход сливаем соседние пары отрезков [lo, mid) и [mid, hi)
из массива src в массив dst => отрезки длины 2 * size
3) меняем src и dst ролями, удваиваем size: 1, 2, 4, 8 ... пока size < n
4) последний отрезок может быть неполным: min(..., n) обрезает границы,
отрезок без правой половины просто копируется
Вместо новых списков на каждом слиянии используем два массива длины n

Корректность: перед проходом с размером size каждый отрезок длины size отсортирован
слияние двух соседних дает отсортированный отрезок длины 2 * size
когда size >= n, отрезок один - весь массив

Quicksort (явный стек вместо стека вызовов)
1) кладем в стек отрезок (0, n - 1)
2) снимаем отрезок, pivot = средний элемент отрезка
3) трехпутевое разбиение за один проход, указатели lt, i, gt:
[low, lt) < pivot, [lt, gt] == pivot, (gt, high] > pivot
4) блок [lt, gt] уже на своих местах, в стек кладем только отрезки длины >= 2:
сначала больший, потом меньший
5) повторяем, пока стек не пуст

Почему так:
- средний pivot: отсортированный и обратный вход делятся пополам
- трехпутевое разбиение: одинаковые элементы отсекаются за один проход
- меньший отрезок снимается первым => в стеке не больше log n отрезков

Корректность: после разбиения левее lt все меньше pivot, правее gt все больше
каждый отрезок в стеке строго короче родителя => цикл завершается

Сложность:
Mergesort
O(n log n) по времени - log n проходов по O(n)
O(n) по памяти - два массива длины n

Quicksort
O(n log n) по времени в среднем - отрезки уменьшаются примерно вдвое
O(n**2) по времени в худшем - только специально подобранный вход
O(n) по памяти - копия входа
O(log n) по памяти на стек - меньший отрезок обрабатывается первым


Визуализация:
mergesort_iter([6, 2, 9, 4, 2, 7, 1])
n = 7 (не степень двойки) и есть повтор 2

Шаг 0:
src = [6, 2, 9, 4, 2, 7, 1]

Шаг 1, size = 1:
[6] + [2] => [2, 6]
[9] + [4] => [4, 9]
[2] + [7] => [2, 7]
[1] без пары => копируем [1]
dst = [2, 6, 4, 9, 2, 7, 1], меняем src и dst

Шаг 2, size = 2:
[2, 6] + [4, 9] => [2, 4, 6, 9]
[2, 7] + [1] => [1, 2, 7]
dst = [2, 4, 6, 9, 1, 2, 7], меняем src и dst

Шаг 3, size = 4:
[2, 4, 6, 9] + [1, 2, 7] => [1, 2, 2, 4, 6, 7, 9]
двойка из левой половины встала раньше двойки из правой (условие <=)
size = 8 >= 7 => стоп, ответ [1, 2, 2, 4, 6, 7, 9]

quicksort_iter([4, 8, 2, 5, 1, 5, 9, 3])
Шаг 1:
стек = [(0, 7)], снимаем (0, 7), pivot = arr[3] = 5
разбиение => [4, 3, 2, 1, 5, 5, 9, 8], равные pivot на местах 4..5
(0, 3) длины 4 больше, (6, 7) длины 2 меньше => кладем (0, 3), потом (6, 7)

Шаг 2:
стек = [(0, 3), (6, 7)], снимаем (6, 7), pivot = arr[6] = 9
разбиение => [..., 8, 9], равные pivot на месте 7
(6, 6) и (8, 7) короче 2 => не кладем

Шаг 3:
стек = [(0, 3)], снимаем (0, 3), pivot = arr[1] = 3
разбиение => [1, 2, 3, 4, ...], равные pivot на месте 2
кладем только (0, 1)

Шаг 4:
стек = [(0, 1)], снимаем (0, 1), pivot = arr[0] = 1
разбиение => [1, 2, ...], оба отрезка короче 2

стек пуст => ответ [1, 2, 3, 4, 5, 5, 8, 9]
максимальный размер стека 2, обе пятерки встали на места за одно разбиение
"""


def _merge_into(src, dst, lo, mid, hi):
    i, j = lo, mid
    for k in range(lo, hi):
        if j >= hi or (i < mid and src[i] <= src[j]):
            dst[k] = src[i]
            i += 1
        else:
            dst[k] = src[j]
            j += 1


def mergesort_iter(arr):
    src = list(arr)
    n = len(src)
    dst = [None] * n
    size = 1
    while size < n:
        for lo in range(0, n, 2 * size):
            mid = min(lo + size, n)
            hi = min(lo + 2 * size, n)
            _merge_into(src, dst, lo, mid, hi)
        src, dst = dst, src
        size *= 2
    return src


def _partition3(arr, low, high):
    pivot = arr[(low + high) // 2]
    lt, i, gt = low, low, high
    while i <= gt:
        if arr[i] < pivot:
            arr[lt], arr[i] = arr[i], arr[lt]
            lt += 1
            i += 1
        elif arr[i] > pivot:
            arr[i], arr[gt] = arr[gt], arr[i]
            gt -= 1
        else:
            i += 1
    return lt, gt


def quicksort_iter(arr, stats=None):
    # stats - необязательный словарь для тестов, в него пишется max_stack
    arr = list(arr)
    stack = [(0, len(arr) - 1)] if len(arr) > 1 else []
    max_stack = len(stack)
    while stack:
        low, high = stack.pop()
        lt, gt = _partition3(arr, low, high)
        left, right = (low, lt - 1), (gt + 1, high)
        if lt - low < high - gt:
            left, right = right, left
        for part in (left, right):
            if part[0] < part[1]:
                stack.append(part)
        max_stack = max(max_stack, len(stack))
    if stats is not None:
        stats["max_stack"] = max_stack
    return arr


