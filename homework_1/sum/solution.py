"""
№2. Максимальная сумма, делящаяся на 2

Решение: жадный алгоритм
берем сумму всех элементов
- Если она чётна - это ответ (больше взять нельзя)
- Если нечётна - нужно убрать ровно один нечетный элемент
Убираем наименьший нечетный, чтобы потеря была минимальной
- Если нечетных нет (невозможно при нечетной сумме четных), ответ 0

Корректность: сумма четных чисел всегда четна. Значит нечетная
итоговая сумма возникает только если в массиве есть хотя бы один
нечетный элемент. Удаление одного нечетного числа переводит нечетную
сумму в четную; удаление двух нечетных тоже, но сумма меньше.
Поэтому оптимально удалить ровно один - наименьший нечетный.

Сложность:
O(n) по времени - суммирование
O(1) по памяти - только для нескольких переменных-констант

Визуализация:
[5, 7, 13, 2, 14]

Сумма = 5+7+13+2+14 = 41  (нечетная)
Нечетные элементы: 5, 7, 13
Минимальный нечетный: 5
Ответ = 41 − 5 = 36
"""


def max_even_sum(nums: list[int]) -> int:
    total = sum(nums)

    if total % 2 == 0:
        return total

    # ищем минимальный нечетный элемент для удаления
    min_odd = min((x for x in nums if x % 2 == 1), default=None)
    if min_odd is None:
        return 0

    return total - min_odd


if __name__ == "__main__":
    nums = list(map(int, input().split()))
    print(max_even_sum(nums))
